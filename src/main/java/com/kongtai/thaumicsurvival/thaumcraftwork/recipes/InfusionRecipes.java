package com.kongtai.thaumicsurvival.thaumcraftwork.recipes;

/**
 * ============================================================
 * 【普通注魔配方管理类（幼儿园宝宝版）】
 * ============================================================
 * 这个类专门放“注魔祭坛”的配方（有中心物品、周围要摆东西、要扣源质的那种）。
 * 
 * 【⭐ 今天的最新架构（最重要的一课）】
 * 以前你写注魔配方，要定义一个变量 public static InfusionRecipe recipeXxx;
 * 现在不需要了！你只要调用 TCRecipes.infusion("研究KEY", ...)，
 * 底层就会自动把它分类，塞进专属的“分拣机”里。
 * 
 * 【配套写书的方法】
 * 在 TSResearchRegistry 里，只要写 .infusionPage()，
 * 书里就会自动把这个 KEY 名下所有的注魔配方全抓出来，在一页里循环翻页！
 * ============================================================
 */
public class InfusionRecipes {

    /**
     * 总入口。
     * 在 CommonProxy.init() 里调用 InfusionRecipes.init()
     */
    public static void init() {
        // ==========================================
        // 普通注魔配方写在这里
        // 目前这里是空的，咱们给你写一个被注释掉的“完美例子”
        // ==========================================

        /*
         * // 👇 【完美例子】：注魔一个“魔法钻石”
         * AspectList cost = TCAspects.of(
         * TCAspects.MAGIC, 16, // 要 16 点魔力
         * TCAspects.AURA, 8, // 要 8 点灵气
         * TCAspects.SENSES, 8 // 要 8 点感知
         * );
         * // 基座材料：4个，方便玩家对称摆
         * ItemStack[] components = new ItemStack[] {
         * TCItems.diamond(),
         * TCItems.diamond(),
         * TCItems.salisMundus(), // 世界盐
         * TCItems.salisMundus()
         * };
         * // 真正注册配方！
         * TCRecipes.infusion(
         * "THAUMICSURVIVAL_MAGIC_DIAMOND", // ① 研究 key（和节点一致）
         * TCItems.diamond(), // ② 输出：合成出啥？
         * 5, // ③ 不稳定度（0~10日常，20~50危险）
         * cost, // ④ 源质菜单（要扣的要素）
         * TCItems.ironIngot(), // ⑤ 中心物品（放祭坛正中间）
         * components // ⑥ 基座材料（周围摆的）
         * );
         * // 注意：写完上面这句，配方就注册好了！不需要手动存进任何 List 里！
         */
    }

    // ============================================================
    // 【👇 注魔配方 · 幼儿园级别避坑大百科 👇】
    // ============================================================
    // 写新配方的时候，如果忘了怎么填，直接抄上面的例子，然后看下面的坑！

    // ------------------------------------------------------------
    // 【宝宝坑点 1】怎么给合成出来的物品加 NBT 标签？
    // ------------------------------------------------------------
    // 比如你想合成一把自带特殊名字的剑，普通的 ItemStack 不够用。
    // 你只要用 TCRecipes.infusionNBT(...) 就行了，输出参数写成这样：
    //
    // new Object[] {
    // "thaumicsurvival:anvil_tier", // NBT 的名字
    // new NBTTagByte((byte) 1) // NBT 的值
    // }
    //
    // 注意：一次只能贴一个标签。如果要贴很多标签，得用 NBTTagCompound 包起来（高级操作）。

    // ------------------------------------------------------------
    // 【宝宝坑点 2】为什么祭坛总是说“无匹配配方”？
    // ------------------------------------------------------------
    // 因为 A 哥的底层是个极其挑剔的教导主任，他会检查 4 件事：
    // ① 你的研究 KEY 对上了吗？
    // ② 祭坛正中间放的东西对吗？
    // ③ 周围要的材料，少放了吗？
    // ④ 周围是不是多放了东西？
    // 👉 重点：只要基座上多丢了一个垃圾，祭坛立刻罢工！千万提醒玩家别手滑。

    // ------------------------------------------------------------
    // 【宝宝坑点 3】研究 KEY 必须一模一样！
    // ------------------------------------------------------------
    // 配方里写的 "THAUMICSURVIVAL_MAGIC_DIAMOND"，
    // 必须和书里 Research.of("THAUMICSURVIVAL_MAGIC_DIAMOND") 一字不差。
    // 少一个字母、大小写错了，甚至多了一个空格，玩家就算解锁了也合不出来！
    // 如果实在想给所有人都能合（不限制研究），KEY 就填 ""（空字符串）。

    // ------------------------------------------------------------
    // 【宝宝坑点 4】基座材料能写矿物词典（矿辞）吗？
    // ------------------------------------------------------------
    // 不能直接传字符串（比如 "ingotIron" 会报错）。
    // 你必须传具体的物品（比如 TCItems.ironIngot()）。
    // 但是别担心，底层在匹配的时候会自动兼容。你放了原版的铁锭，
    // 别的模组的铁锭只要注册了矿辞，祭坛一样认。

    // ------------------------------------------------------------
    // 【宝宝坑点 5】不稳定度（instability）到底填多少？
    // ------------------------------------------------------------
    // 0~5：非常安全，偶尔掉点小垃圾。
    // 5~15：有点危险，会喷咒波，可能炸掉。
    // 15~40：极其危险，雷劈、爆炸、咒波满天飞。
    // 40+ ：谁合谁死。
    // 日常物品填个 1~5 就行了，终极神装填个 15~25。

    // ------------------------------------------------------------
    // 【宝宝坑点 6】基座材料到底要几个？
    // ------------------------------------------------------------
    // 注魔祭坛周围有 4 个基座位置。
    // 你传 4 个材料，玩家每个基座放 1 个。
    // 你传 8 个材料，玩家每个基座放 2 个。
    // 强烈建议写 4、6、8、12，因为好对称摆放，强迫症玩家看着舒服。
}
